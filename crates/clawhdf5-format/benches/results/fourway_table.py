#!/usr/bin/env python3
"""Render fourway.csv (from examples/fourway_bench.rs) as LaTeX tables.

Usage: python3 fourway_table.py fourway.csv [fourway-ed25519-nofast.csv] > fourway.tex

Times are the median of the 30 measured trials; the 95% bootstrap CI
(2000 resamples, same protocol as hash_bench_harness.rs/baselines_bench.rs)
is computed per cell and its widest relative half-width is reported in the
caption. Requires booktabs; the sweep table also needs multirow.
"""
import csv
import re
import random
import statistics
import sys
from collections import defaultdict

BACKENDS = [
    ("merkle_sha256", r"Merkle (SHA-256)"),
    ("merkle_blake3", r"Merkle (BLAKE3)"),
    ("flat_sha256", r"Flat SHA-256"),
    ("hmac_sha256", r"Per-chunk HMAC-SHA-256"),
    ("ed25519", r"Per-chunk Ed25519"),
]
OPS = ["commit", "verify_dataset", "verify_chunk", "update", "append"]
DATASETS = [
    ("dataset_64kb", "64\\,KiB"),
    ("dataset_256kb", "256\\,KiB"),
    ("dataset_1mb", "1\\,MiB"),
    ("Rad", "NOAA"),
]


def load(path, rename=None):
    timed, fixed, meta = defaultdict(list), {}, {}
    with open(path) as f:
        header = f.readline()
        for r in csv.DictReader(f):
            b = rename.get(r["backend"], r["backend"]) if rename else r["backend"]
            key = (r["dataset"], b, r["metric"])
            meta[r["dataset"]] = (int(r["n_chunks"]), float(r["chunk_size_kb"]))
            if r["unit"] == "ns":
                timed[key].append(int(r["value"]))
            else:
                fixed[key] = r["value"]
    return header.strip(), timed, fixed, meta


def bootstrap_ci(xs, reps=2000, seed=0):
    rng = random.Random(seed)
    meds = sorted(
        statistics.median(rng.choices(xs, k=len(xs))) for _ in range(reps)
    )
    return meds[int(0.025 * reps)], meds[int(0.975 * reps) - 1]


def fmt_time(ns):
    if ns >= 1e9:
        return f"{ns / 1e9:.2f}\\,s"
    if ns >= 1e6:
        return f"{ns / 1e6:.1f}\\,ms" if ns < 1e8 else f"{ns / 1e6:.0f}\\,ms"
    if ns >= 1e3:
        return f"{ns / 1e3:.1f}\\,\\textmu s" if ns < 1e5 else f"{ns / 1e3:.0f}\\,\\textmu s"
    return f"{ns:.0f}\\,ns"


def fmt_bytes(b):
    b = int(b)
    # Switch units at 1000 of the smaller unit so 1,048,544 B reads as 1.00 MiB.
    for unit, scale in (("MiB", 2**20), ("KiB", 2**10)):
        if b >= 1000 * scale / 1024:
            v = b / scale
            return f"{v:.2f}\\,{unit}" if v < 100 else f"{v:.0f}\\,{unit}"
    return f"{b}\\,B"


def fmt_n(n):
    return f"{n:,}".replace(",", "{,}")


def cell(timed, fixed, ds, b, op, worst):
    xs = timed.get((ds, b, op))
    if not xs:
        return "---" if fixed.get((ds, b, op)) == "unsupported" else "?"
    med = statistics.median(xs)
    lo, hi = bootstrap_ci(xs)
    if med > 0:
        worst[0] = max(worst[0], (hi - lo) / 2 / med)
    return fmt_time(med)


def main():
    header, timed, fixed, meta = load(sys.argv[1])
    backends = list(BACKENDS)
    if len(sys.argv) > 2:
        _, t2, f2, _ = load(sys.argv[2], {"ed25519": "ed25519_nofast"})
        timed.update(t2)
        fixed.update(f2)
        backends.append(("ed25519_nofast", r"Per-chunk Ed25519 (no \texttt{fast})"))

    worst = [0.0]
    out = []
    out.append(f"% Generated by fourway_table.py from {sys.argv[1]}")
    out.append("% " + re.sub(r"hostname=\S+ ", "", header))

    # ── Table 1: full capability comparison at the 256 KiB cell ──────────────
    ds = "dataset_256kb"
    n, kb = meta[ds]
    rows = []
    for b, label in backends:
        times = [cell(timed, fixed, ds, b, op, worst) for op in OPS]
        md = fixed.get((ds, b, "metadata_bytes"))
        pb = fixed.get((ds, b, "chunk_proof_bytes"))
        pub = fixed.get((ds, b, "public_verification"))
        rows.append(
            f"{label} & "
            + " & ".join(times)
            + f" & {fmt_bytes(md) if md else '?'}"
            + f" & {'---' if pb in (None, 'unsupported') else fmt_bytes(pb)}"
            + f" & {'Yes' if pub == 'yes' else 'No'} \\\\"
        )
    out += [
        r"\begin{table*}[t]",
        r"  \centering",
        r"  \small",
        f"  \\caption{{Integrity-backend comparison on the synthetic "
        f"256\\,KiB-chunk dataset ($N={fmt_n(n)}$ chunks, {n * kb / 2**20:.2f}\\,GiB). "
        r"Times are medians of 30 single-threaded trials after 5 discarded "
        r"warm-ups; all backends were measured in one run on the same host. "
        r"Ed25519 uses \texttt{ed25519-dalek} with precomputed tables (\texttt{fast}). "
        r"\emph{Verify chunk} is a verifier holding only the trusted commitment "
        r"(Merkle root + inclusion proof, HMAC key + tag, or Ed25519 public key + "
        r"signature). \emph{Proof} is the per-chunk evidence a verifier must "
        r"receive. --- marks an operation the backend cannot perform; flat "
        r"SHA-256 update/append are full rehashes.}",
        r"  \label{tab:fourway-256k}",
        r"  \begin{tabular}{l rrrrr rrc}",
        r"    \toprule",
        r"    & \multicolumn{5}{c}{Time (median)} & \multicolumn{2}{c}{Storage} & \\",
        r"    \cmidrule(lr){2-6} \cmidrule(lr){7-8}",
        r"    Backend & Commit & Verify dataset & Verify chunk & Update & Append "
        r"& Metadata & Proof & Public \\",
        r"    \midrule",
    ]
    out += ["    " + r for r in rows]
    out += [r"    \bottomrule", r"  \end{tabular}", r"\end{table*}", ""]

    # ── Table 2: time sweep across every dataset ─────────────────────────────
    out += [
        r"\begin{table*}[t]",
        r"  \centering",
        r"  \small",
        r"  \caption{Median time per operation across chunk sizes "
        r"(synthetic datasets: 3.33\,GiB each; NOAA GOES-18 \texttt{Rad}: "
        f"{meta['Rad'][0]} DEFLATE-compressed chunks, "
        f"{meta['Rad'][1]:.1f}\\,KiB average on disk). Same protocol as "
        r"Table~\ref{tab:fourway-256k}.}",
        r"  \label{tab:fourway-sweep}",
        r"  \begin{tabular}{ll " + "r" * len(DATASETS) + "}",
        r"    \toprule",
        r"    Operation & Backend & "
        + " & ".join(
            f"{lab} ($N={fmt_n(meta[d][0])}$)" for d, lab in DATASETS
        )
        + r" \\",
    ]
    op_labels = {
        "commit": "Commit",
        "verify_dataset": "Verify dataset",
        "verify_chunk": "Verify chunk",
        "update": "Update",
        "append": "Append",
    }
    for op in OPS:
        out.append(r"    \midrule")
        for i, (b, label) in enumerate(backends):
            first = (
                f"\\multirow{{{len(backends)}}}{{*}}{{{op_labels[op]}}}" if i == 0 else ""
            )
            vals = [cell(timed, fixed, d, b, op, worst) for d, _ in DATASETS]
            out.append(f"    {first} & {label} & " + " & ".join(vals) + r" \\")
    out += [r"    \bottomrule", r"  \end{tabular}", r"\end{table*}"]

    out.insert(
        2,
        f"% Widest 95% bootstrap CI half-width across all cells: "
        f"{worst[0] * 100:.2f}% of the median.",
    )
    print("\n".join(out))


if __name__ == "__main__":
    main()
